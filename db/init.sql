-- The one schema definition, shared by both services: the coordinator is the
-- only writer and the API only reads. Postgres runs this file once, when the
-- data volume is first created (`docker compose down -v` resets it). In
-- production this would become the first Flyway migration.

CREATE TABLE birthdays (
    id                       uuid        PRIMARY KEY,  -- generated by the API, one per submission
    name                     text        NOT NULL,
    email                    text        NOT NULL,     -- reminder recipient
    birthday                 date        NOT NULL,
    reminder_window_days     smallint    NOT NULL CHECK (reminder_window_days BETWEEN 1 AND 14),
    gift_ideas               text,
    last_reminded_occurrence date,                     -- set after a reminder is published
    created_at               timestamptz NOT NULL DEFAULT now()
);
